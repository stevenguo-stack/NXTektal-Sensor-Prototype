inline void drawMarkOnce() {
  for (int i = 0; i < LOGO_W * LOGO_H; ++i) {
    const uint8_t packed = pgm_read_byte(&logo4bpp[i >> 1]);
    const uint8_t paletteIndex = (i & 1) ? (packed & 0xF) : (packed >> 4);
    const uint16_t native = pgm_read_word(&logoPalette[paletteIndex]);
    logoFrame[i] = (native >> 8) | (native << 8);
  }
  display.st7735_draw_image(6, 21, LOGO_W, LOGO_H, logoFrame);
}

